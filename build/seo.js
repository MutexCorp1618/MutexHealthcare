/* Search, social and answer-engine markup shared by every page.

   SET THIS ONCE THE SITE HAS AN ADDRESS: the full web address with no trailing slash,
   for example 'https://www.example.com'. While it is empty the build leaves out the things
   that need an absolute address: canonical links, sitemap.xml and the Sitemap line in robots.txt. */
'use strict';
const SITE_URL = 'https://mutexhealthcare.vercel.app';

const UPDATED = '2026-11-16'; // shown to search engines as the date articles were last reviewed
const OG_IMAGE = 'assets/og-image.png';

/* Page addresses are shown without "index" or ".html":  about.html -> about,  index.html -> ./  */
const clean = (href) => String(href).replace(/^index\.html/, './').replace(/\.html(?=$|[?#])/, '');
const abs = (p = '') => (SITE_URL ? `${SITE_URL}/${clean(p).replace(/^\.\//, '')}` : clean(p));
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const strip = (s) => String(s).replace(/<[^>]+>/g, '').replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/\s+/g, ' ').trim();

function organization(MX) {
  const S = MX.SITE;
  const [, city, region, zip] = /^(.+),\s*([A-Z]{2})\s+(\d{5})/.exec(S.address[1]) || [];
  return {
    '@type': 'EmploymentAgency',
    ...(SITE_URL ? { '@id': SITE_URL + '/#organization', url: SITE_URL + '/' } : {}),
    name: S.name,
    description: 'Healthcare staffing agency placing nurses, therapists, allied health, imaging, pharmacy, behavioral health and healthcare IT professionals with hospitals, clinics, schools and agencies across the United States.',
    slogan: 'One opening, one right clinician, one accountable recruiter.',
    telephone: S.phoneHref.replace('tel:', ''),
    email: S.email,
    logo: abs('assets/brand/mutex-healthcare-logo.svg'),
    image: abs(OG_IMAGE),
    address: { '@type': 'PostalAddress', streetAddress: S.address[0], addressLocality: city, addressRegion: region, postalCode: zip, addressCountry: 'US' },
    areaServed: { '@type': 'Country', name: 'United States' },
    knowsAbout: ['Travel nursing', 'Healthcare staffing', 'Per diem staffing', 'Permanent placement', 'Credentialing and compliance', ...MX.SPECIALTIES.map((s) => s.name + ' staffing')],
  };
}

/* page: { file, title, desc, crumbs: [[label, href?]], faqs: [[q, a]], article?: true, noindex?: true } */
function graph(page, MX) {
  const g = [organization(MX)];
  const orgRef = SITE_URL ? { '@id': SITE_URL + '/#organization' } : { '@type': 'Organization', name: MX.SITE.name };
  if (page.file === 'index.html') {
    g.push({ '@type': 'WebSite', ...(SITE_URL ? { '@id': SITE_URL + '/#website', url: SITE_URL + '/' } : {}), name: MX.SITE.name, publisher: orgRef, inLanguage: 'en-US' });
  }
  g.push({
    '@type': page.article ? 'Article' : 'WebPage',
    ...(SITE_URL ? { url: abs(page.file) } : {}),
    [page.article ? 'headline' : 'name']: strip(page.title),
    description: strip(page.desc),
    inLanguage: 'en-US',
    ...(page.article ? { datePublished: UPDATED, dateModified: UPDATED, author: orgRef, publisher: orgRef, image: abs(OG_IMAGE) } : { isPartOf: { '@type': 'WebSite', name: MX.SITE.name } }),
  });
  if (page.crumbs && page.crumbs.length) {
    g.push({
      '@type': 'BreadcrumbList',
      itemListElement: [['Home', 'index.html'], ...page.crumbs].map(([name, href], i, all) => ({
        '@type': 'ListItem', position: i + 1, name: strip(name),
        ...(i < all.length - 1 || href ? { item: abs(href || page.file) } : { item: abs(page.file) }),
      })),
    });
  }
  if (page.faqs && page.faqs.length) {
    g.push({
      '@type': 'FAQPage',
      mainEntity: page.faqs.map(([q, a]) => ({ '@type': 'Question', name: strip(q), acceptedAnswer: { '@type': 'Answer', text: strip(a) } })),
    });
  }
  return { '@context': 'https://schema.org', '@graph': g };
}

/* The block of tags that goes inside <head> */
function head(page, MX) {
  const title = esc(strip(page.title)), desc = esc(strip(page.desc));
  const ld = JSON.stringify(graph(page, MX)).replace(/</g, '\\u003c');
  return `<!-- seo:start (generated by build/build.js, do not edit by hand) -->
  <meta name="robots" content="${page.noindex ? 'noindex, follow' : 'index, follow, max-snippet:-1, max-image-preview:large'}">${SITE_URL ? `
  <link rel="canonical" href="${abs(page.file)}">
  <meta property="og:url" content="${abs(page.file)}">` : ''}
  <meta property="og:site_name" content="${esc(MX.SITE.name)}">
  <meta property="og:type" content="${page.article ? 'article' : 'website'}">
  <meta property="og:title" content="${title}">
  <meta property="og:description" content="${desc}">
  <meta property="og:image" content="${abs(OG_IMAGE)}">
  <meta property="og:image:width" content="1200">
  <meta property="og:image:height" content="630">
  <meta property="og:image:alt" content="${esc(MX.SITE.name)}: one opening, one right clinician.">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:title" content="${title}">
  <meta name="twitter:description" content="${desc}">
  <meta name="twitter:image" content="${abs(OG_IMAGE)}">
  <meta name="theme-color" content="#0f5fcb">
  <script type="application/ld+json">${ld}</script>
  <!-- seo:end -->`;
}

/* Plain links shown only when scripts do not run, so crawlers that skip JavaScript can still find every page */
const GROUPS = [
  ['For clinicians', (f) => /^(jobs|job-seekers|travel-nursing|allied-therapy|per-diem|permanent-placement|federal-schools|healthcare-it|specialt|locations|pay-benefits|licensure|referral|apply)/.test(f)],
  ['For healthcare organizations', (f) => /^(employers|staffing-|workforce-solutions|contract-therapy|credentialing-compliance|rural-critical-access|mutex-match)/.test(f)],
  ['Company and guides', () => true],
];
function grouped(pages) {
  const left = pages.filter((p) => p.file !== 'index.html' && p.file !== '404.html');
  return GROUPS.map(([title, test]) => {
    const mine = left.filter((p) => !p.taken && test(p.file));
    mine.forEach((p) => { p.taken = true; });
    return [title, mine];
  });
}
function fallbackNav(pages) {
  pages.forEach((p) => { delete p.taken; });
  const header = `<div id="site-header"><nav class="nojs-nav" aria-label="Site"><a href="./"><b>Mutex Healthcare Staffing</b></a> <a href="jobs">Find jobs</a> <a href="employers">Staffing services</a> <a href="workforce-solutions">Workforce solutions</a> <a href="mutex-match">Mutex Match</a> <a href="about">About</a> <a href="contact">Contact</a></nav></div>`;
  const footer = `<div id="site-footer"><nav class="nojs-nav nojs-foot" aria-label="All pages">${grouped(pages).map(([title, list]) =>
    `<p><b>${title}:</b> ${list.map((p) => `<a href="${clean(p.file)}">${esc(strip(p.short || p.title))}</a>`).join(' ')}</p>`).join('')}</nav></div>`;
  return { header, footer };
}

function llmsTxt(pages, MX) {
  const S = MX.SITE;
  pages.forEach((p) => { delete p.taken; });
  const lines = [
    `# ${S.name}`,
    '',
    '> Healthcare staffing agency that places nurses, therapists, allied health, imaging, pharmacy, behavioral health and healthcare IT professionals with hospitals, clinics, schools and agencies in all 50 US states.',
    '',
    'Key facts:',
    `- What we do: travel contracts, local contracts, per diem shifts and permanent placement for clinicians; staffing, workforce programs and credentialing for healthcare organizations.`,
    '- How we work: one opening, one right clinician, one recruiter accountable for the match. Every job posting shows the pay before you apply.',
    '- Specialties: ' + MX.SPECIALTIES.map((s) => s.name).join(', ') + '.',
    `- Head office: ${S.address.join(', ')}, United States.`,
    `- Phone: ${S.phone}. Email: ${S.email}. Hours: ${S.hours}.`,
    '- Response time: clinicians and facilities hear back within one business day.',
    '',
  ];
  grouped(pages).forEach(([title, list]) => {
    lines.push(`## ${title}`, '');
    list.forEach((p) => lines.push(`- [${strip(p.short || p.title)}](${abs(p.file)}): ${strip(p.desc)}`));
    lines.push('');
  });
  return lines.join('\n');
}

function robotsTxt() {
  const bots = ['GPTBot', 'OAI-SearchBot', 'ChatGPT-User', 'ClaudeBot', 'Claude-SearchBot', 'Claude-User', 'PerplexityBot', 'Perplexity-User', 'Google-Extended', 'Applebot-Extended', 'Bingbot', 'CCBot'];
  return [
    '# Search engines and AI answer engines are welcome to read this site.',
    'User-agent: *',
    'Allow: /',
    'Disallow: /build/',
    '',
    ...bots.flatMap((b) => [`User-agent: ${b}`, 'Allow: /', 'Disallow: /build/', '']),
    ...(SITE_URL ? [`Sitemap: ${SITE_URL}/sitemap.xml`, ''] : ['# Add the Sitemap line by setting SITE_URL in build/seo.js and rebuilding.', '']),
  ].join('\n');
}

function sitemapXml(pages) {
  if (!SITE_URL) return '';
  const urls = pages.filter((p) => !p.noindex && p.file !== '404.html').map((p) =>
    `  <url><loc>${abs(p.file)}</loc><lastmod>${UPDATED}</lastmod><priority>${p.file === 'index.html' ? '1.0' : /^(jobs|employers|job-seekers|about)/.test(p.file) ? '0.8' : '0.6'}</priority></url>`);
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join('\n')}\n</urlset>\n`;
}

module.exports = { SITE_URL, UPDATED, head, fallbackNav, llmsTxt, robotsTxt, sitemapXml, strip, clean };
