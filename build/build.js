/* Last step for every page:
   - links lose "index" and ".html" (about.html -> about); vercel.json turns on cleanUrls so these work
   - css and js links get ?v=<fingerprint of the file>, so they can be cached for a long time
   - photo addresses written for any image service (also in the hand-written pages) are rewritten
     for the one chosen in MX.SITE.imageCdn */
const crypto = require('crypto');
const stamp = {};
const fingerprint = (rel) => stamp[rel] || (stamp[rel] = crypto.createHash('md5').update(fs.readFileSync(path.join(ROOT, rel))).digest('hex').slice(0, 8));

/* Photo versions: every people-photo address carries ?v=<fingerprint of the photo>, so a replaced photo
   gets a new address and no browser keeps showing an old copy. js/photo-versions.js gives the same list
   to the scripts that draw photos (MX.img). */
const PEOPLE_DIR = path.join(ROOT, 'assets', 'people');
MX.PHOTO_V = Object.fromEntries(fs.readdirSync(PEOPLE_DIR).filter((f) => f.endsWith('.jpg')).sort()
  .map((f) => [f.slice(0, -4), fingerprint(`assets/people/${f}`)]));
out('js/photo-versions.js', `/* Generated by build/build.js. A fingerprint for each photo in assets/people/, so that a replaced
   photo gets a new address (MX.img adds ?v=). Do not edit by hand. */
(window.MX = window.MX || {}).PHOTO_V = ${JSON.stringify(MX.PHOTO_V)};
`);
const photoV = (name) => (MX.PHOTO_V[name] ? `?v=${MX.PHOTO_V[name]}` : '');

const imgUrl = (src, w) => MX.img(src, Number(w)).replace(/&/g, '&amp;');
function finish(html) {
  return html
    .replace(/\/\.netlify\/images\?url=\/([^&"]+)&amp;w=(\d+)(?:&amp;[a-z]+=[\w]+)*/g, (m, src, w) => imgUrl(src, w))
    .replace(/\/_vercel\/image\?url=%2F([^&"]+)&amp;w=(\d+)(?:&amp;[a-z]+=[\w]+)*/g, (m, src, w) => imgUrl(decodeURIComponent(src), w))
    .replace(/assets\/people\/(?:(\d+)\/)?([\w-]+)\.jpg(?:\?v=\w+)?/g, (m, w, name) => (w ? imgUrl(`assets/people/${name}.jpg`, w) : `assets/people/${name}.jpg${photoV(name)}`))
    .replace(/href="(?!https?:|\/|#|mailto:|tel:)([a-z0-9-]+)\.html((?:[?#][^"]*)?)"/g, (m, name, rest) => (name === 'index' ? `href="./${rest}"` : `href="${name}${rest}"`))
    .replace(/(href|src)="((?:css|js)\/[\w.-]+\.(?:css|js))(?:\?v=\w+)?"/g, (m, attr, rel) => `${attr}="${rel}?v=${fingerprint(rel)}"`)
    .replace(/href="assets\/favicon\.svg(?:\?v=\w+)?"/g, () => `href="assets/favicon.svg?v=${fingerprint('assets/favicon.svg')}"`);
}

